# MAIN CONVERSATIONAL DISPATCHER FUNCTION
# ==============================================================================
def chat_with_guanena(
    message: str,
    chat_history: Optional[List[Dict[str, str]]] = None,
    user_lat: Optional[float] = 1.2148,
    user_lng: Optional[float] = -77.2780,
    requested_day: Optional[str] = "4 de enero"
) -> Dict[str, Any]:
    """Execute conversational dispatching using Gemini 2.0 Flash with real-time GPS telemetry.

    Args:
        message: Natural language prompt from the user.
        chat_history: Optional list of previous message turns.
        user_lat: Real-time user GPS latitude (defaults to Plaza de Nariño).
        user_lng: Real-time user GPS longitude (defaults to Plaza de Nariño).
        requested_day: Optional carnival day of interest.

    Returns:
        Dict matching CarnavalChatResponse schema with schedule, route, and sorted nearby places.
    """
    if chat_history is None:
        chat_history = []

    if user_lat is None:
        user_lat = 1.2148
    if user_lng is None:
        user_lng = -77.2780

    # Compute nearest POIs from user's current GPS position
    nearby_sorted = get_nearest_pois(user_lat, user_lng)

    api_key = settings.GEMINI_API_KEY.strip() if hasattr(settings, "GEMINI_API_KEY") else ""
    if not api_key:
        api_key = os.getenv("GEMINI_API_KEY", "")

    # If valid Gemini API key is configured and google-genai is available
    if api_key and api_key not in ["tu_clave_de_gemini_aqui", ""] and genai is not None:
        try:
            client = genai.Client(api_key=api_key)

            # Build history string
            history_context = ""
            if chat_history:
                formatted_history = "\n".join(
                    f"{turn.get('role', 'user')}: {turn.get('content', '')}"
                    for turn in chat_history[-6:]
                )
                history_context = f"\nPrevious Conversation:\n{formatted_history}\n"

            closest_pois_summary = "\n".join(
                f"- {p['name']} ({p['category']}): {p['address']} a {int(p['distance_meters'])} m ({p['proximity_label']})"
                for p in nearby_sorted[:5]
            )

            prompt_content = f"""{history_context}
User Real-time GPS Location: [{user_lat}, {user_lng}]
Requested Day: "{requested_day}"
User Query: "{message}"

Closest Verified Points of Interest to User:
{closest_pois_summary}

Instructions:
Explicitly name the single closest facility with exact meters/blocks away: "Te encuentras a X metros de [Lugar], el más cercano es...".
Always return SENDA_OFFICIAL_PATH in route_coordinates whenever the user asks for the Senda, dates, or navigation.
"""

            model_name = getattr(settings, "GEMINI_MODEL", "gemini-3.5-flash")
            try:
                response = client.models.generate_content(
                    model=model_name,
                    contents=prompt_content,
                    config=types.GenerateContentConfig(
                        system_instruction=GUANENA_SYSTEM_PROMPT,
                        response_mime_type="application/json",
                        response_schema=GuaneñaStructuredResponse,
                        temperature=0.3,
                    )
                )
            except Exception as primary_err:
                logger.warning(f"Aviso con {model_name} ({primary_err}). Reintentando con gemini-3.1-flash-lite...")
                response = client.models.generate_content(
                    model="gemini-3.1-flash-lite",
                    contents=prompt_content,
                    config=types.GenerateContentConfig(
                        system_instruction=GUANENA_SYSTEM_PROMPT,
                        response_mime_type="application/json",
                        response_schema=GuaneñaStructuredResponse,
                        temperature=0.3,
                    )
                )

            if response and response.text:
                cleaned_text = _clean_json_text(response.text)
                data = json.loads(cleaned_text)

                route_coords = data.get("route_coordinates", [])
                if not route_coords:
                    route_coords = SENDA_OFFICIAL_PATH

                schedule_obj = data.get("schedule")
                if not schedule_obj:
                    schedule_obj = get_schedule_for_query(requested_day or message)

                places_out = data.get("nearby_places", [])
                if not places_out:
                    places_out = nearby_sorted

                return {
                    "reply": data.get("reply", "¡Qué viva Pasto, carajo!"),
                    "schedule": schedule_obj,
                    "should_draw_route": True,
                    "route_coordinates": route_coords,
                    "waypoints": route_coords,
                    "nearby_places": places_out,
                    "suggested_questions": data.get("suggested_questions", [
                        "¿Dónde quedan los baños públicos autorizados?",
                        "¿Dónde puedo comer cuy típico cerca a la Senda?",
                        "¿Cuál es el recorrido exacto de la Senda del Carnaval?"
                    ])
                }
        except Exception as exc:
            logger.warning(
                f"[GEMINI_SERVICE] Notice while querying Gemini 2.0 Flash ({type(exc).__name__}: {exc}). "
                "Engaging deterministic cultural GIS fallback with Haversine proximity."
            )

    # Deterministic fallback when Gemini API is unavailable or offline
    return _deterministic_fallback(
        message=message,
        user_lat=user_lat,
        user_lng=user_lng,
        requested_day=requested_day
    )
