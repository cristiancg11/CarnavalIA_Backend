    msg = message.lower().strip()
    schedule_data = get_schedule_for_query(requested_day or message)

    # Detect requested category
    target_category = None
    if any(k in msg for k in ["baño", "baños", "sanitario", "sanitarios", "batería", "bateria", "orinar", "chichi", "restroom", "bathroom"]):
        target_category = "bathroom"
    elif any(k in msg for k in ["policia", "policía", "cai", "seguridad", "denuncia", "robo", "perdido"]):
        target_category = "cai"
    elif any(k in msg for k in ["salud", "cruz roja", "primeros auxilios", "ambulancia", "hospital", "médico", "medico", "emergencia"]):
        target_category = "health"
    elif any(k in msg for k in ["restaurante", "comer", "comida", "cuy", "gastronomia", "gastronomía", "cafe", "café", "almorzar", "empanada"]):
        target_category = "restaurant"
    elif any(k in msg for k in ["tarima", "tarimas", "musica", "música", "concierto", "conciertos", "orquesta", "escenario", "baile"]):
        target_category = "stage"

    # Query nearest POIs sorted by Haversine distance
    sorted_pois = get_nearest_pois(user_lat, user_lng, category=target_category)
    closest_poi = sorted_pois[0] if sorted_pois else None

